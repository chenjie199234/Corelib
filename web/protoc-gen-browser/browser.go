func genFileComment(plugin *protogen.Plugin, g *protogen.GeneratedFile, source string) {
	//add version comments
	g.P("// Code generated by protoc-gen-browser. DO NOT EDIT.")
	g.P("// versions:")
	protocVersion := "(unknown)"
	if v := plugin.Request.GetCompilerVersion(); v != nil {
		protocVersion = fmt.Sprintf("v%v.%v.%v", v.GetMajor(), v.GetMinor(), v.GetPatch())
		if s := v.GetSuffix(); s != "" {
			protocVersion += "-" + s
		}
	}
	g.P("// \tprotoc-gen-browser ", version.String())
	g.P("// \tprotoc             ", protocVersion)
	g.P("// source: ", source)
	g.P()
}

func genEnum(plugin *protogen.Plugin, e *protogen.Enum, dir string) {
	f := plugin.NewGeneratedFile(dir+"/browser_enum_"+string(e.Desc.ParentFile().Package())+"_"+string(e.GoIdent.GoName)+".ts", "")
	genFileComment(plugin, f, e.Desc.ParentFile().Path())
	f.P("export enum ", e.GoIdent.GoName, "{")
	for i, v := range e.Values {
		for comment := range strings.SplitSeq(strings.TrimSuffix(v.Comments.Leading.String(), "\n"), "\n") {
			if comment == "" {
				continue
			}
			f.P("\t", comment)
		}
		if i == len(e.Values)-1 {
			if v.Comments.Trailing.String() != "" {
				f.P("\t", v.Desc.Name(), "=", v.Desc.Number(), strings.TrimSuffix(v.Comments.Trailing.String(), "\n"))
			} else {
				f.P("\t", v.Desc.Name(), "=", v.Desc.Number())
			}
		} else {
			if v.Comments.Trailing.String() != "" {
				f.P("\t", v.Desc.Name(), "=", v.Desc.Number(), ",", strings.TrimSuffix(v.Comments.Trailing.String(), "\n"))
			} else {
				f.P("\t", v.Desc.Name(), "=", v.Desc.Number(), ",")
			}
		}
	}
	f.P("}")
}
